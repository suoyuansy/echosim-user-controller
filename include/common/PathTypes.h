#pragma once

#include <vector>

// 定义全局规划、路径优化和轨迹跟踪三大模块共用的二维位姿与路径点类型。
// 字段与单位约定是跨模块的冻结接口，见 docs/模块接口说明.md。
// 坐标系与单位总约定：所有坐标均为仿真世界坐标系（与地形查询 API 一致，
// 直接传 (X, Y)，不对 Y 取负）；长度单位为米，角度单位为弧度；
// 航向以世界 X 轴正方向为零、逆时针为正（即 atan2(dy, dx) 约定）。
struct Pose2D
{
    double x = 0.0;   // 世界坐标 X，单位为米。
    double y = 0.0;   // 世界坐标 Y，单位为米。
    double yaw = 0.0; // 航向角，单位为弧度；X 轴正方向为零，逆时针为正。
};

// 路径中的一个离散参考点：三大模块间传递路径的最小单元。
// 字段含义与 Pose2D 完全一致（世界坐标，米/弧度）；yaw 表示该点处的
// 路径切向航向，由优化模块按相邻点差分重算，跟踪模块用作参考方向。
struct PathPoint
{
    double x = 0.0;   // 路径点世界坐标 X，单位为米。
    double y = 0.0;   // 路径点世界坐标 Y，单位为米。
    double yaw = 0.0; // 路径点航向角，单位为弧度；为该点处路径切向（优化后由差分重算）。
};

// 路径：按行驶方向（起点 -> 终点）有序排列的路径点序列。
// 模块一（全局规划）产出原始栅格路径，模块二（优化）精简/平滑后输出，
// 交给模块三（跟踪）作为参考线；首点即起点，末点即目标点，
// 序列顺序隐含行进方向。
using Path = std::vector<PathPoint>;
